"""Build complete, demand-loaded WenKai coverage from the unchanged original.

Requires fonttools[woff] 4.55.3 and Brotli 1.0.9. No dependency is needed at app
runtime or for ordinary builds: generated font assets and hashes are checked in.
Run with --check to verify coverage, outlines and metrics without rebuilding.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import unicodedata
from pathlib import Path

import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/assets/fonts/LXGWWenKai-Regular.ttf"
OUTPUT = ROOT / "src/assets/fonts/wenkai"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def ranges(points: set[int]) -> str:
    spans: list[tuple[int, int]] = []
    for n in sorted(points):
        if spans and spans[-1][1] + 1 == n:
            spans[-1] = (spans[-1][0], n)
        else:
            spans.append((n, n))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


def ideograph(n: int) -> bool:
    return (0x3400 <= n <= 0x9FFF or 0xF900 <= n <= 0xFAFF or
            0x20000 <= n <= 0x323AF)


def variation_selectors(font: TTFont) -> set[int]:
    return {n for table in font["cmap"].tables if table.format == 14 for n in table.uvsDict}


def expand_ranges(value: str) -> set[int]:
    points: set[int] = set()
    for item in value.split(","):
        bounds = item.removeprefix("U+").split("-")
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        points.update(range(start, end + 1))
    return points


def write_definitions(manifest: dict) -> None:
    original = TTFont(SOURCE)
    original_points = set(original.getBestCmap())
    selectors = variation_selectors(original)
    imports, rows = [], []
    for index, part in enumerate(manifest["parts"]):
        coverage = expand_ranges(part["unicodeRange"])
        if part["common"]:
            # Inputs such as Hangul Jamo may have no direct cmap glyph, but
            # HarfBuzz can compose them into supported syllables. A restrictive
            # CSS unicode-range must not bypass the font before shaping them.
            inputs = {ord(char) for cp in coverage for char in unicodedata.normalize("NFD", chr(cp))}
            coverage |= selectors | (inputs - original_points)
        imports.append(f'import part{index} from "./{part["file"]}?url";')
        rows.append(f'  {{ source: part{index}, unicodeRange: "{ranges(coverage)}", common: {str(part["common"]).lower()} }},')
    (OUTPUT / "parts.ts").write_text("// Generated by scripts/build-interface-font.py; full original retained for recovery.\n" +
        "\n".join(imports) + "\n\nexport const WENKAI_PARTS = [\n" + "\n".join(rows) + "\n];\n", encoding="utf-8")


def build() -> None:
    original = TTFont(SOURCE, recalcTimestamp=False)
    points = set(original.getBestCmap())
    used: set[int] = set()
    for directory in [ROOT / "src", ROOT.parent / "src/shared"]:
        for path in directory.rglob("*"):
            if path.suffix in (".ts", ".tsx") and ".test." not in path.name and "gen" not in path.parts:
                used.update(map(ord, path.read_text(encoding="utf-8")))
    # All non-ideographic scripts and their spaces stay in one font run. Splitting
    # Hangul from punctuation changes native run rasterization, even with equal
    # glyph outlines and advances. Only remaining CJK ideographs are deferred.
    variation_bases = {n for table in original["cmap"].tables if table.format == 14
                       for mappings in table.uvsDict.values() for n, _glyph in mappings}
    common = {n for n in points if not ideograph(n) or n in used or n in variation_bases}
    groups = [("common", common)]
    remaining = sorted(points - common)
    for start in range(0, len(remaining), 256):
        groups.append((f"cjk-{start // 256:04x}", set(remaining[start:start + 256])))
    selectors = variation_selectors(original)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    old_files = set()
    if (OUTPUT / "manifest.json").exists():
        old_files = {p["file"] for p in json.loads((OUTPUT / "manifest.json").read_text(encoding="utf-8"))["parts"]}
    parts = []
    for index, (name, coverage) in enumerate(groups):
        if not coverage:
            continue
        font = TTFont(SOURCE, recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ["*"]
        options.layout_scripts = ["*"]
        options.glyph_names = True
        options.notdef_outline = True
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        processor = subset.Subsetter(options=options)
        processor.populate(unicodes=coverage | (selectors if name == "common" else set()))
        processor.subset(font)
        font.flavor = "woff2"
        filename = name + ".woff2"
        path = OUTPUT / filename
        font.save(path)
        unicode_range = ranges(coverage)
        part = {"file": filename, "sha256": digest(path), "bytes": path.stat().st_size,
                "characters": len(coverage), "unicodeRange": unicode_range, "common": name == "common"}
        parts.append(part)
        print(f"{filename}: {len(coverage)} characters, {path.stat().st_size} bytes", flush=True)
    manifest = {"sourceSha256": digest(SOURCE), "characters": len(points),
                "fontTools": fontTools.__version__, "brotli": brotli.__version__, "parts": parts}
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_definitions(manifest)
    for filename in old_files - {part["file"] for part in parts}:
        path = (OUTPUT / filename).resolve()
        assert path.parent == OUTPUT.resolve() and re.fullmatch(r"(?:common|korean|cjk-[a-f0-9]+)\.woff2", filename)
        path.unlink(missing_ok=True)


def outline(font: TTFont, name: str):
    glyph = font["glyf"][name]
    coordinates, ends, flags = glyph.getCoordinates(font["glyf"])
    instructions = glyph.program.getBytecode() if hasattr(glyph, "program") else b""
    return list(coordinates), list(ends), list(flags), instructions, font["hmtx"][name]


def check() -> None:
    manifest = json.loads((OUTPUT / "manifest.json").read_text(encoding="utf-8"))
    assert digest(SOURCE) == manifest["sourceSha256"], "Original font changed"
    original = TTFont(SOURCE)
    expected = original.getBestCmap()
    covered: set[int] = set()
    original_outlines = {}
    compared = 0
    for part in manifest["parts"]:
        path = OUTPUT / part["file"]
        assert digest(path) == part["sha256"], f"Font segment changed: {path.name}"
        font = TTFont(path)
        cmap = font.getBestCmap()
        assert not covered.intersection(cmap), "Character ownership overlaps"
        assert len(cmap) == part["characters"]
        assert ranges(set(cmap)) == part["unicodeRange"]
        covered.update(cmap)
        for codepoint, name in cmap.items():
            assert name == expected[codepoint], f"Changed glyph mapping: U+{codepoint:X}"
        # Include substitution/composite/variation glyphs, not just Unicode cmap.
        for name in font.getGlyphOrder():
            if name not in original_outlines:
                original_outlines[name] = outline(original, name)
            assert outline(font, name) == original_outlines[name], f"Changed outline or metric: {name}"
            compared += 1
        for table in font["cmap"].tables:
            if table.format == 14:
                source_table = next(t for t in original["cmap"].tables if t.format == 14)
                for selector, mappings in table.uvsDict.items():
                    assert all(pair in source_table.uvsDict[selector] for pair in mappings), "Changed variation mapping"
    assert covered == set(expected), "Coverage is incomplete"
    assert len(covered) == manifest["characters"]
    print(json.dumps({"completeCoverage": len(covered), "segments": len(manifest["parts"]),
                      "outlinesAndMetricsCompared": compared, "originalUnchanged": True}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if not arguments.check:
        build()
    check()
